"""Generate compact, antialiased Lato glyphs for the minimal GIGA display.

Requires Pillow and the Ubuntu fonts-lato package. Run from the repository root.
Glyph coverage is quantized to 4 bits and stored in flash, not allocated at runtime.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "firmware/giga-filament"
FONTS = Path("/usr/share/fonts/truetype/lato")
SPECS = [
    ("clockFont", "Lato-Light.ttf", 104, "0123456789:-"),
    ("valueFont", "Lato-Regular.ttf", 72, "0123456789.- CF%°"),
    ("labelFont", "Lato-Regular.ttf", 24, "FILAMENT BOX TEMPERATURE HUMIDITY 0123456789-"),
    ("statusFont", "Lato-Regular.ttf", 22, "Connecting...Waiting for fresh sensor dataLive"),
]


def main():
    lines = ["// Generated by tools/generate_filament_fonts.py; see FONT-LICENSE.txt.",
             "#pragma once", "#include <stdint.h>",
             "struct SmoothGlyph { uint8_t code; int16_t left, top; uint16_t width, height, advance; uint32_t offset; };",
             "struct SmoothFont { const SmoothGlyph* glyphs; const uint8_t* pixels; uint16_t count, ascent; };"]
    previews = {}
    for name, filename, size, chars in SPECS:
        path = FONTS / filename
        font = ImageFont.truetype(str(path), size)
        pixels, glyphs, images = [], [], {}
        lines.append(f"// {filename}, {size}px, SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}")
        for char in sorted(set(chars)):
            left, top, right, bottom = font.getbbox(char, anchor="ls")
            width, height = right-left, bottom-top
            advance = round(font.getlength(char))
            offset = len(pixels)
            if width and height:
                im = Image.new("L", (width, height))
                ImageDraw.Draw(im).text((-left, -top), char, font=font, fill=255, anchor="ls")
                coverage = [(value+8)//17 for value in im.tobytes()]
                for i in range(0, len(coverage), 2):
                    pixels.append((coverage[i] << 4) | (coverage[i+1] if i+1 < len(coverage) else 0))
                im = Image.frombytes("L", (width, height), bytes(value*17 for value in coverage))
                images[char] = (im, left, top, advance)
            else:
                images[char] = (None, left, top, advance)
            glyphs.append(f"  {{{ord(char)}, {left}, {top}, {width}, {height}, {advance}, {offset}}},")
        lines += [f"static const uint8_t {name}Pixels[] = {{"]
        lines += ["  " + ",".join(str(v) for v in pixels[i:i+32]) + "," for i in range(0, len(pixels), 32)]
        lines += ["};", f"static const SmoothGlyph {name}Glyphs[] = {{", *glyphs, "};",
                  f"static const SmoothFont {name} = {{{name}Glyphs, {name}Pixels, {len(glyphs)}, {font.getmetrics()[0]}}};"]
        previews[name] = (images, font.getmetrics()[0])
    (DEST / "smooth_font.h").write_text("\n".join(lines) + "\n")
    license_text = Path("/usr/share/doc/fonts-lato/copyright").read_text()
    (DEST / "FONT-LICENSE.txt").write_text("\n".join(line.rstrip() for line in license_text.splitlines()) + "\n")
    preview = Image.new("RGB", (800, 480))

    def text(value, name, center, y, color):
        images, ascent = previews[name]
        x = center - sum(images[c][3] for c in value)//2
        for char in value:
            mask, left, top, advance = images[char]
            if mask is not None:
                preview.paste(color, (x+left, y+ascent+top), mask)
            x += advance

    date = "2026-10-22"
    date_width = sum(previews["labelFont"][0][c][3] for c in date)
    text(date, "labelFont", 776 - (date_width+1)//2, 12, (144, 150, 160))
    text("22:54:08", "clockFont", 400, 35, (245, 247, 250))
    text("OUTDOOR", "labelFont", 210, 185, (0, 255, 128))
    text("FILAMENT", "labelFont", 590, 185, (0, 255, 128))
    text("11.0 °C", "valueFont", 210, 228, (245, 247, 250))
    text("24.4 °C", "valueFont", 590, 228, (245, 247, 250))
    text("68.2 %", "valueFont", 210, 330, (245, 247, 250))
    text("34.8 %", "valueFont", 590, 330, (245, 247, 250))
    text("Live", "statusFont", 400, 440, (144, 150, 160))
    output = ROOT / "build/giga-filament/font-preview.png"
    output.parent.mkdir(parents=True, exist_ok=True)
    preview.save(output)


if __name__ == "__main__":
    main()
